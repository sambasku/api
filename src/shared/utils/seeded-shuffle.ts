/**
 * Acak deterministik per seed (FNV-1a 32-bit -> mulberry32).
 * Seed sama = urutan sama, seed beda = urutan beda. Dipakai deck vote dan
 * antrean review supaya tiap user dapat urutan kartu sendiri tanpa bikin
 * pagination (cursor keyset) goyang: yang diacak hanya isi halaman.
 */
export function seededShuffle<T>(items: readonly T[], seed: string): T[] {
  let h = 2166136261;
  for (let i = 0; i < seed.length; i++) {
    h ^= seed.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }

  const next = (): number => {
    h = (h + 0x6d2b79f5) | 0;
    let t = Math.imul(h ^ (h >>> 15), 1 | h);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };

  const out = [...items];
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(next() * (i + 1));
    [out[i], out[j]] = [out[j] as T, out[i] as T];
  }
  return out;
}
